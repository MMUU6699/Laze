package app.vela.core.voice

/**
 * Adapts standard Modern Standard Arabic navigation utterances into familiar spoken Iraqi Arabic
 * navigation dialect (e.g. "لف يمنة", "لف يسرة", "الفلكة", "استدير وارجع", "ضل مكمل كبل").
 */
object IraqiVoicePhrases {

    /**
     * Adapts [text] if [enabled] is true. Otherwise returns [text] unmodified.
     */
    fun adapt(text: String, enabled: Boolean = true): String {
        if (!enabled || text.isBlank()) return text
        var result = text

        for ((regex, replacement) in REPLACEMENTS) {
            result = regex.replace(result, replacement)
        }
        return result
    }

    private val REPLACEMENTS: List<Pair<Regex, String>> = listOf(
        // U-turns: دوران للخلف
        Regex("""(قم بالدوران للخلف|انعطف للخلف|استدر للخلف|قم بدوران للخلف|قم بالالتفاف للخلف)""") to "استدير وارجع",

        // Roundabout: الفلكة
        Regex("""في الدوّ?ار""") to "بالفلكة",
        Regex("""عند الدوّ?ار""") to "عند الفلكة",
        Regex("""ادخل الدوّ?ار""") to "ادخل الفلكة",
        Regex("""اخرج من الدوّ?ار""") to "اطلع من الفلكة",
        Regex("""الدوّ?ار""") to "الفلكة",
        Regex("""دوّ?ار""") to "فلكة",
        Regex("""المخرج الأول""") to "أول مخرج",
        Regex("""المخرج الثاني""") to "ثاني مخرج",
        Regex("""المخرج الثالث""") to "ثالث مخرج",
        Regex("""المخرج الرابع""") to "رابع مخرج",

        // Turns: يمنة ويسرة
        Regex("""(انعطف|اتجه)\s+(إلى\s+اليمين|يميناً|يمينا|نحو\s+اليمين|لليمين)""") to "لف يمنة",
        Regex("""(انعطف|اتجه)\s+(إلى\s+اليسار|يساراً|يسارا|نحو\s+اليسار|لليسار)""") to "لف يسرة",
        Regex("""(الزم|ابقَ? في|ابقَ? على)\s+(المسار الأيمن|اليمين)""") to "الزم اليمنة",
        Regex("""(الزم|ابقَ? في|ابقَ? على)\s+(المسار الأيسر|اليسار)""") to "الزم اليسرة",
        Regex("""على اليمين""") to "على اليمنة",
        Regex("""على اليسار""") to "على اليسرة",

        // Continue straight: ضل مكمل كبل
        Regex("""(استمر في السير إلى الأمام|استمر للأمام|استمر إلى الأمام|سر إلى الأمام|واصل السير للأمام|استمر بالسير مستقيماً|استمر مستقيماً|سر مستقيماً|تابع السير مستقيماً)""") to "ضل مكمل كبل",
        Regex("""(استمر|واصل)\s+على\s+نفس\s+الطريق""") to "ضل مكمل على نفس الطريق",

        // Distances: المسافات باللهجة العراقية
        Regex("""بعد\s+(200|مائتي|مئتي)\s+متر""") to "بعد ميتين متر",
        Regex("""بعد\s+(100|مائة|مئة)\s+متر""") to "بعد مية متر",
        Regex("""بعد\s+(300|ثلاثمائة|ثلاثمئة)\s+متر""") to "بعد تلثمية متر",
        Regex("""بعد\s+(400|أربعمائة|أربعمئة)\s+متر""") to "بعد أربعمية متر",
        Regex("""بعد\s+(500|خمسمائة|خمسمئة)\s+متر""") to "بعد نص كيلو",
        Regex("""بعد\s+(1|١)?\s*(كيلومتر|كم)\s*(واحد)?""") to "بعد كيلومتر",
        Regex("""بعد\s+(2|٢|كيلومترين)\s*(كيلومتر|كم)?""") to "بعد كيلوين",

        // Arrival & alerts: الوصول والتنبيهات
        Regex("""(لقد وصلت إلى وجهتك|وصلت إلى وجهتك|لقد وصلت إلى الوجهة|وصلت إلى الوجهة)""") to "وصلت بالسلامة",
        Regex("""(جاري إعادة حساب المسار|أعد حساب المسار|إعادة حساب المسار)""") to "دا نعيد حساب الطريق",
        Regex("""طريق أسرع متاح""") to "أكو طريق أسرع",
    )
}
